#!/bin/bash
# FLOW → Cloudflare Workers (бесплатно).
#   ./deploy.sh                     → адрес вида https://flow.<ник>.workers.dev
#   ./deploy.sh flow.torg-lot.ru    → свой поддомен (домен должен быть в твоём Cloudflare)
# Повторный запуск = обновление. Токен бота спрашивается один раз, ввод скрыт.
set -euo pipefail
cd "$(dirname "$0")"
DOMAIN="${1:-}"
W="npx --yes wrangler@4"

command -v node >/dev/null || { echo "❌ Нужен Node.js — поставь с https://nodejs.org и запусти снова"; exit 1; }

echo "① Собираю мини-апп…"
node build.mjs

echo "② Проверяю вход в Cloudflare…"
if ! $W whoami 2>/dev/null | grep -qi "logged in"; then
  echo "   Откроется браузер — войди в Cloudflare и нажми Allow."
  $W login
fi

echo "③ Хранилище библиотеки (KV)…"
if [ ! -s .kv-id ]; then
  out=$(CI=true $W kv namespace create flow-lib 2>&1 || true)
  id=$(echo "$out" | grep -oE '"?id"?[[:space:]]*[:=][[:space:]]*"[0-9a-f]{32}"' | grep -oE '[0-9a-f]{32}' | head -1 || true)
  if [ -z "$id" ]; then
    # Already exists from an earlier run: look it up.
    id=$(CI=true $W kv namespace list 2>/dev/null | node -e 'let s="";process.stdin.on("data",d=>s+=d).on("end",()=>{try{const l=JSON.parse(s.slice(s.indexOf("[")));const n=l.find(x=>/flow-lib/.test(x.title));console.log(n?n.id:"")}catch{console.log("")}})')
  fi
  [ -n "$id" ] || { echo "$out"; echo "❌ Не получилось создать KV"; exit 1; }
  echo "$id" > .kv-id
fi
KV=$(cat .kv-id)

ROUTES=""
[ -n "$DOMAIN" ] && ROUTES=",
  \"routes\": [{ \"pattern\": \"$DOMAIN\", \"custom_domain\": true }]"
cat > wrangler.jsonc <<JSON
{
  // Generated by deploy.sh
  "name": "flow",
  "main": "src/worker.js",
  "compatibility_date": "2025-09-01",
  "workers_dev": true,
  "assets": { "directory": "./public", "binding": "ASSETS", "run_worker_first": true },
  "kv_namespaces": [{ "binding": "LIB", "id": "$KV" }]$ROUTES
}
JSON

echo "④ Деплой…"
if ! $W deploy; then
  echo "❌ Деплой не прошёл (см. выше)"
  [ -n "$DOMAIN" ] && echo "   Если ругается на домен — попробуй без него: ./deploy.sh"
  exit 1
fi

if ! $W secret list 2>/dev/null | grep -q BOT_TOKEN; then
  echo
  echo "⑤ Вставь токен бота от @BotFather (символы не видны — так и надо) и нажми Enter:"
  $W secret put BOT_TOKEN
fi

echo
if [ -n "$DOMAIN" ]; then
  URL="https://$DOMAIN"
  echo "✅ Готово: $URL"
  echo "   Ссылка мини-аппа для BotFather: $URL/"
  echo "   Открываю настройку бота: $URL/api/setup.php  (новому домену может понадобиться 1–2 минуты)"
  sleep 5
  open "$URL/api/setup.php" 2>/dev/null || true
else
  echo "✅ Готово! Возьми адрес https://flow.….workers.dev из строк выше и открой:"
  echo "   <адрес>/api/setup.php   — настройка бота"
  echo "   <адрес>/                — ссылка мини-аппа для BotFather"
fi
